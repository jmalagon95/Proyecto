import assert from 'node:assert/strict';
import { TOWER_FLOORS, normalizeTowerProgress, canEnterTowerFloor, clearTowerFloor, getTowerParty } from '../src/systems/tower-progression.js';
assert.equal(TOWER_FLOORS.length,30);
assert.equal(TOWER_FLOORS[0].floor,1);
assert.equal(TOWER_FLOORS[29].floor,30);
assert.equal(TOWER_FLOORS.filter(f=>f.boss).length,6);
assert.ok(TOWER_FLOORS.every((f,i)=>i===0||f.enemyHPPercent>=TOWER_FLOORS[i-1].enemyHPPercent));
let state=normalizeTowerProgress(null);
assert.equal(state.unlockedFloor,1);
assert.equal(canEnterTowerFloor(state,2),false);
let r=clearTowerFloor(state,1);
assert.equal(r.ok,true);
assert.deepEqual(r.rewards,{coins:TOWER_FLOORS[0].coins,xp:TOWER_FLOORS[0].xp});
state=r.state;
assert.equal(state.unlockedFloor,2);
assert.equal(clearTowerFloor(state,1).rewards,null);
assert.equal(clearTowerFloor(state,4).ok,false);
assert.equal(getTowerParty([{id:'x',name:'Kairakh',stats:{FUE:12},currentStar:1,dead:false},{id:'y',dead:true}],['x']).length,1);
console.log('Tower progression tests passed');
